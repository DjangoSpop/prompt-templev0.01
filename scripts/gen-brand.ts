/**
 * Sprint 11 — regenerates src/lib/brand.ts from src/styles/brand-v2.css so the
 * hex tokens used by image routes / manifest never drift from the stylesheet.
 * Run: npm run brand:gen
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const css = readFileSync(resolve(process.cwd(), 'src/styles/brand-v2.css'), 'utf8');

const KEYS: Record<string, string> = {
  ground: '--ground', surface: '--surface', ink: '--ink', inkMuted: '--ink-muted', line: '--line',
  faience: '--faience', faienceFill: '--faience-fill', onFaience: '--on-faience', lapis: '--lapis',
  gilt: '--gilt', giltLine: '--gilt-line',
};

function block(selector: string): string {
  const i = css.indexOf(selector);
  if (i < 0) throw new Error(`selector not found: ${selector}`);
  const start = css.indexOf('{', i);
  const end = css.indexOf('\n}', start);
  return css.slice(start, end);
}

function pick(src: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(KEYS)) {
    const m = new RegExp(`${v.replace(/-/g, '\\-')}:\\s*(#[0-9a-fA-F]{3,8})`).exec(src);
    if (!m) throw new Error(`token not found: ${v}`);
    out[k] = m[1];
  }
  return out;
}

const light = pick(block('html[data-brand="v2"] {'));
const dark = pick(block('html[data-brand="v2"].dark {'));

const fmt = (o: Record<string, string>) =>
  Object.entries(o).map(([k, v]) => `    ${k}: '${v}',`).join('\n');

const out = `// GENERATED by scripts/gen-brand.ts from src/styles/brand-v2.css — do not edit by hand.
// Sprint 11 identity flag + the brand hex tokens for code that cannot read CSS variables
// (OG/share image routes, manifest, scripts).

export const BRAND_V2 = process.env.NEXT_PUBLIC_THEME_V2 === 'true';

/** Conditionally add v2-only class names (keeps the old theme byte-identical when the flag is off). */
export const v2cls = (...classes: string[]): string => (BRAND_V2 ? classes.join(' ') : '');

export const brand = {
  light: {
${fmt(light)}
  },
  dark: {
${fmt(dark)}
  },
} as const;

export type BrandTheme = keyof typeof brand;
`;

writeFileSync(resolve(process.cwd(), 'src/lib/brand.ts'), out);
console.log('src/lib/brand.ts written');
